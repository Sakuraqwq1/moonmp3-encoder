#!/usr/bin/env python3
"""Generate deterministic audio fixtures for encoder development.

Every fixture is synthetic, so it can be regenerated byte-for-byte from this
script without shipping audio in the repository. Each entry is written twice:

    <name>.wav   PCM_16 WAV for decoders and measurement tools
    <name>.pcm   interleaved little-endian int16 for the MoonBit CLI

A manifest records rate, channels, frames, peak, RMS and SHA-256 digests, so
a debugging session can state exactly which material produced a result.

Usage:
    python tools/gen_fixtures.py                 # target/fixtures
    python tools/gen_fixtures.py --out D:/fixtures
    python tools/gen_fixtures.py --list
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "target", "fixtures")
RATE = 44100
SEED = 20261101


def tone(rate: int, seconds: float, frequency: float, amplitude: float) -> np.ndarray:
    t = np.arange(int(rate * seconds), dtype=np.float64) / rate
    return amplitude * np.sin(2.0 * np.pi * frequency * t)


def signals(seed: int):
    """Yield (name, description, float64[frames, channels]) in a fixed order."""
    one = tone(RATE, 1.0, 440.0, 0.5)
    yield "sine440_mono_1s", "440 Hz sine, -6 dBFS, mono", one[:, None]

    left = tone(RATE, 1.0, 440.0, 0.5)
    right = tone(RATE, 1.0, 660.0, 0.5)
    yield "sine440_stereo_1s", "440 Hz left / 660 Hz right, mono-independent stereo", np.column_stack([left, right])

    yield "sine1k_mono_500ms", "1 kHz sine, -12 dBFS, mono", tone(RATE, 0.5, 1000.0, 0.25)[:, None]

    t = np.arange(RATE, dtype=np.float64) / RATE
    multi = (
        np.sin(2 * np.pi * 440 * t)
        + 0.5 * np.sin(2 * np.pi * 880 * t)
        + 0.25 * np.sin(2 * np.pi * 1320 * t)
    )
    multi *= 0.6 / np.max(np.abs(multi))
    yield "multitone_mono_1s", "440/880/1320 Hz partials, mono", multi[:, None]

    duration = 0.5
    t = np.arange(int(RATE * duration), dtype=np.float64) / RATE
    f0, f1 = 100.0, 8000.0
    phase = 2 * np.pi * (f0 * t + (f1 - f0) * t * t / (2 * duration))
    yield "chirp_mono_500ms", "100 Hz to 8 kHz linear chirp, mono", (0.5 * np.cos(phase))[:, None]

    rng = np.random.default_rng(seed)
    noise = 0.2 * rng.uniform(-1.0, 1.0, int(RATE * 0.5))
    yield "noise_mono_500ms", "uniform white noise, seed recorded in manifest", noise[:, None]

    yield "silence_mono_1s", "digital silence, mono", np.zeros((RATE, 1), dtype=np.float64)

    impulse = np.zeros((int(RATE * 0.5), 2), dtype=np.float64)
    impulse[int(RATE * 0.25), 0] = 0.9
    impulse[int(RATE * 0.25), 1] = -0.9
    yield "impulse_stereo_500ms", "single opposite-polarity sample pair at 250 ms", impulse

    yield "fullscale_mono_1s", "440 Hz sine at 0.99 peak, mono", tone(RATE, 1.0, 440.0, 0.99)[:, None]

    yield "dc_mono_500ms", "constant +0.1 DC, mono edge case", np.full((int(RATE * 0.5), 1), 0.1, dtype=np.float64)


def pcm16_array(data: np.ndarray) -> np.ndarray:
    """Convert float samples to interleaved little-endian int16."""
    scaled = np.round(data * 32768.0)
    return np.clip(scaled, -32768, 32767).astype("<i2")


def pcm16_bytes(data: np.ndarray) -> bytes:
    """Interleave and serialise int16 samples without a second conversion."""
    return pcm16_array(data).reshape(-1).tobytes()


def sha256(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build(out_dir: str, seed: int) -> dict:
    import soundfile as sf

    os.makedirs(out_dir, exist_ok=True)
    entries = []
    for name, description, data in signals(seed):
        if data.ndim != 2:
            raise ValueError(f"{name}: expected 2-D samples")
        peak = float(np.max(np.abs(data))) if data.size else 0.0
        rms = float(np.sqrt(np.mean(np.square(data)))) if data.size else 0.0
        wav_path = os.path.join(out_dir, name + ".wav")
        pcm_path = os.path.join(out_dir, name + ".pcm")
        pcm = pcm16_array(data)
        sf.write(wav_path, pcm, RATE, format="WAV", subtype="PCM_16")
        with open(pcm_path, "wb") as handle:
            handle.write(pcm.reshape(-1).tobytes())
        back, rate = sf.read(wav_path, always_2d=True, dtype="int16")
        if rate != RATE or back.shape != data.shape or not np.array_equal(back, pcm):
            raise RuntimeError(f"{name}: WAV round-trip changed rate, shape or samples")
        entries.append(
            {
                "name": name,
                "description": description,
                "wav": os.path.basename(wav_path),
                "pcm": os.path.basename(pcm_path),
                "rate": RATE,
                "channels": int(data.shape[1]),
                "frames": int(data.shape[0]),
                "seconds": round(data.shape[0] / RATE, 6),
                "peak": round(peak, 8),
                "rms": round(rms, 8),
                "wav_sha256": sha256(wav_path),
                "pcm_sha256": sha256(pcm_path),
            }
        )
    manifest = {
        "generator": "tools/gen_fixtures.py",
        "generator_version": 1,
        "seed": seed,
        "rate": RATE,
        "encoding": "pcm_s16le interleaved",
        "fixtures": entries,
    }
    path = os.path.join(out_dir, "manifest.json")
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(manifest, handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    return manifest


def list_fixtures(seed: int) -> int:
    for name, description, data in signals(seed):
        print(f"{name:24s} {data.shape[0]:6d} frames  {data.shape[1]} ch  {description}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=DEFAULT_OUT, help="output directory (default: target/fixtures)")
    parser.add_argument("--seed", type=int, default=SEED, help="noise seed recorded in the manifest")
    parser.add_argument("--list", action="store_true", help="list fixtures without writing files")
    parser.add_argument("--quiet", action="store_true", help="only print the manifest path")
    args = parser.parse_args()

    if args.list:
        return list_fixtures(args.seed)
    manifest = build(args.out, args.seed)
    if not args.quiet:
        for entry in manifest["fixtures"]:
            print(
                f"{entry['name']:24s} {entry['seconds']:5.3f}s "
                f"{entry['channels']} ch  peak={entry['peak']:.4f}  {entry['wav_sha256'][:12]}"
            )
    print(f"manifest: {os.path.join(args.out, 'manifest.json')}")
    print(f"fixtures: {len(manifest['fixtures'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
